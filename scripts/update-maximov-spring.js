const AUTUMN_MONTHS = new Set(['09', '10', '11', '12'])

const isAutumn = (entry) =>
  Array.isArray(entry.dates) && entry.dates.length > 0 && entry.dates.every((d) => AUTUMN_MONTHS.has(d.split('.')[1]))

const spring = rows.map(([day, time, group, type, subject, room, dates]) => ({
  day: DAYS[day],
  time,
  dates,
  group,
  type: TYPES[type],
  subject: SUBJECTS[subject],
  room,
  teacher: null,
  parity: null,
}))

const current = JSON.parse(fs.readFileSync(outputs[0], 'utf8'))
const autumn = current.filter(isAutumn)
const previousSpring = current.filter((e) => !isAutumn(e))

const key = (e) => [e.day, e.time, e.group, e.type, e.subject, e.room, e.dates.join(' ')].join('|')
const before = new Set(previousSpring.map(key))
const after = new Set(spring.map(key))
const added = spring.filter((e) => !before.has(key(e)))
const removed = previousSpring.filter((e) => !after.has(key(e)))

console.log(`Осенних пар сохранено: ${autumn.length}`)
console.log(`Весенних пар было: ${previousSpring.length}, стало: ${spring.length}`)
if (added.length) {
  console.log(`\nДобавлено (${added.length}):`)
  added.forEach((e) => console.log(`  + ${key(e)}`))
}
if (removed.length) {
  console.log(`\nУдалено (${removed.length}):`)
  removed.forEach((e) => console.log(`  - ${key(e)}`))
}

if (process.argv.includes('--dry')) {
  console.log('\n[dry] файлы не изменены')
} else {
  const json = `${JSON.stringify([...autumn, ...spring], null, 2)}\n`
  for (const outputPath of outputs) {
    fs.writeFileSync(outputPath, json, 'utf8')
    console.log(`Wrote ${path.relative(rootDir, outputPath)} (${autumn.length + spring.length} lessons)`)
  }
}
