function titleCase(s){
  return s.split(' ').map(w=> w ? w[0]+w.slice(1).toLowerCase() : w).join(' ')
}
function normalizeTeacher(raw){
  if(!raw) return null
  // "МАКСИМОВ РОМАН СЕРГЕЕВИЧ" -> "Максимов Р.С."
  const parts = raw.trim().split(/\s+/)
  if(parts.length>=3){
    const fam = titleCase(parts[0])
    const ini = parts[1][0].toUpperCase() + '.' + parts[2][0].toUpperCase() + '.'
    return `${fam} ${ini}`
  }
  return titleCase(raw)
}

